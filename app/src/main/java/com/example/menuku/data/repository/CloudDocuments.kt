package com.example.menuku.data.repository

import com.example.menuku.data.models.*

/** The document ID is owned by Firestore; calendar dates use UTC epoch days. */
object CloudDocuments {
    fun stock(item: StockItem): Map<String, Any> = mapOf(
        "name" to item.name, "quantity" to item.quantity, "unit" to item.unit,
        "location" to item.location.id, "locationLabel" to item.location.label,
        "locationDescription" to item.location.tempDesc, "category" to item.category,
        "purchaseDate" to item.purchaseDate, "expiryEpochDay" to item.expiryEpochDay,
        "note" to item.note, "imageUrl" to item.imageUrl, "matchedRecipes" to item.matchedRecipes
    )
    fun stock(id: String, data: Map<String, Any>): StockItem {
        val locationId = data.text("location")
        val standard = listOf(StorageLocation.KULKAS, StorageLocation.FREEZER, StorageLocation.PANTRI)
        val location = standard.find { it.id.equals(locationId, true) } ?: StorageLocation(
            locationId, data.text("locationLabel"), data.text("locationDescription")
        )
        val day = (data["expiryEpochDay"] as? Number)?.toLong()
            ?: error("Tanggal kedaluwarsa bahan belum valid: $id")
        return StockItem(id, data.text("name"), data.number("quantity").toDouble(), data.text("unit"),
            location, data.text("category"), data.text("purchaseDate"), StockDates.format(day),
            (day - StockDates.todayEpochDay()).toInt(), data.text("imageUrl"), data.text("note"),
            data.strings("matchedRecipes"), day)
    }
    fun schedule(item: MealSchedule): Map<String, Any> = mapOf(
        "dateStr" to item.dateStr, "dayName" to item.dayName, "dayNumber" to item.dayNumber,
        "slot" to item.slot.name, "recipeIds" to item.allRecipes.map { it.id },
        "reminderTime" to item.reminderTime, "reminderEnabled" to item.reminderEnabled,
        "note" to item.note, "autoSyncGrocery" to item.autoSyncGrocery
    )
    fun schedule(id: String, data: Map<String, Any>, recipes: List<Recipe>): MealSchedule {
        val selected = data.strings("recipeIds").mapNotNull { recipeId -> recipes.find { it.id == recipeId } }
        return MealSchedule(id, data.text("dateStr"), data.text("dayName"), data.number("dayNumber").toInt(),
            MealSlot.valueOf(data.text("slot")), recipe = selected.firstOrNull(), recipes = selected,
            reminderTime = data.text("reminderTime"), reminderEnabled = data["reminderEnabled"] as? Boolean ?: false,
            note = data.text("note"), autoSyncGrocery = data["autoSyncGrocery"] as? Boolean ?: true)
    }
    fun shopping(item: ShoppingItem): Map<String, Any> = mapOf(
        "name" to item.name, "quantity" to item.quantity, "unit" to item.unit,
        "category" to item.category, "urgency" to item.urgency.name,
        "linkedRecipeTitle" to item.linkedRecipeTitle, "estimatedPrice" to item.estimatedPrice,
        "storeRecommendation" to item.storeRecommendation, "notes" to item.notes,
        "isPurchased" to item.isPurchased, "isAutoGenerated" to item.isAutoGenerated,
        "priceSource" to item.priceSource
    )
    fun shopping(id: String, data: Map<String, Any>) = ShoppingItem(
        id, data.text("name"), data.number("quantity").toDouble(), data.text("unit"), data.text("category"),
        runCatching { UrgencyLevel.valueOf(data.text("urgency")) }.getOrDefault(UrgencyLevel.NORMAL),
        linkedRecipeTitle = data.text("linkedRecipeTitle"), estimatedPrice = data.number("estimatedPrice").toLong(),
        storeRecommendation = data.text("storeRecommendation"), notes = data.text("notes"),
        isPurchased = data["isPurchased"] as? Boolean ?: false,
        isAutoGenerated = data["isAutoGenerated"] as? Boolean ?: false,
        priceSource = data.text("priceSource").ifBlank { "Estimasi rumus" }
    )
    private fun Map<String, Any>.text(key: String) = this[key] as? String ?: ""
    private fun Map<String, Any>.number(key: String): Number = this[key] as? Number ?: 0
    private fun Map<String, Any>.strings(key: String) = (this[key] as? List<*>)?.filterIsInstance<String>().orEmpty()
}
